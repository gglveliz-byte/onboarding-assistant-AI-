/** Filas totales de la malla (48). */
export const EARTH_MAP_ROWS: number = WORLD_MAP_ROWS.length;

/** Columnas totales de la malla (96). */
export const EARTH_MAP_COLS: number = 96;

/** Lectura de una celda con envoltura vertical (las filas fuera de rango actúan como tierra). */
function cellCharAt(row: number, col: number): string {
  if (row < 0 || row >= EARTH_MAP_ROWS) {
    return '1';
  }
  const line = WORLD_MAP_ROWS[row];
  if (line === undefined) {
    return '0';
  }
  return line.charAt(col);
}

/** Construye las celdas de costa (borde) y de masa continental (interior) del mapa. */
function buildEarthCells(): { coast: EarthCell[]; land: EarthCell[] } {
  const coast: EarthCell[] = [];
  const land: EarthCell[] = [];

  for (let row = 0; row < EARTH_MAP_ROWS; row += 1) {
    for (let col = 0; col < EARTH_MAP_COLS; col += 1) {
      if (cellCharAt(row, col) !== '1') {
        continue;
      }
      const lat = (((EARTH_MAP_ROWS * 0.5 - 0.5) - row) / (EARTH_MAP_ROWS * 0.5)) * (Math.PI * 0.5);
      const lon = ((col - (EARTH_MAP_COLS * 0.5 - 0.5)) / (EARTH_MAP_COLS * 0.5)) * Math.PI;

      const isCoast =
        cellCharAt(row - 1, col) === '0' ||
        cellCharAt(row + 1, col) === '0' ||
        cellCharAt(row, (col + EARTH_MAP_COLS - 1) % EARTH_MAP_COLS) === '0' ||
        cellCharAt(row, (col + 1) % EARTH_MAP_COLS) === '0';

      const cell: EarthCell = { lat, lon, row, col };
      if (isCoast) {
        coast.push(cell);
      } else {
        land.push(cell);
      }
    }
  }

  return { coast, land };
}

const EARTH_CELLS = buildEarthCells();

/** Celdas de costa del planeta: reciben el trazo nítido de alta densidad (50 % de la etapa). */
export const EARTH_COAST_CELLS: readonly EarthCell[] = EARTH_CELLS.coast;

/** Celdas interiores de la masa continental: relleno del 36 % de la etapa Tierra. */
